df = pd.DataFrame(data)
df.to_csv('car_data.csv', index=False)

target_col = 'price'
features = [
    'brand',
    'model',
    'city',
    'milage',
    'car_age',
    'fuel_type',
    'transmission',
    'accident',
]
df_model = df[features + [target_col]].copy()

encoding_maps = {}
for col in ['brand', 'model', 'city', 'fuel_type', 'transmission', 'accident']:
  mean_prices = df_model.groupby(col)[target_col].mean().to_dict()
  df_model[col] = df_model[col].map(mean_prices)
  encoding_maps[col] = mean_prices

X = df_model.drop(target_col, axis=1)
y = df_model[target_col]
feature_names = list(X.columns)

# test_size 0.15 rakha hoyeche jate train korar jonno beshi data thake
X_train, X_test, y_train, y_test = train_test_split(
    X.to_numpy(), y.to_numpy(), test_size=0.15, random_state=42
)

model = RandomForestRegressor(n_estimators=100, random_state=42)
model.fit(X_train, y_train)

y_pred = model.predict(X_test)
r2 = r2_score(y_test, y_pred)
mae = mean_absolute_error(y_test, y_pred)
feature_imp = dict(zip(feature_names, model.feature_importances_))

with open('car_price_model.pkl', 'wb') as f:
  pickle.dump((model, feature_names, encoding_maps, r2, mae, feature_imp), f)

print(f'SUCCESS: Model Trained Successfully! R2 Score: {r2:.2f}')